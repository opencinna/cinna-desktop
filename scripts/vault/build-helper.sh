#!/bin/sh
# Builds resources/vault/VaultHelper.app, the Agent Vault helper
# (native/vault/helper), for one flavor (plans/vault-agents D31):
#
#   test     (default) -D VAULT_TEST_GATE: approvals and unlock granted with no
#            prompt, disk key in a plain file, no keychain. Ad-hoc signed with
#            the virtualization entitlement only; needs no Apple account.
#   dev      -D VAULT_DEV: parent check accepts any team-signed Cinna (Apple
#            Development too); own keychain group …vault-helper.dev.
#   release  parent check (D26), LocalAuthentication, Secure Enclave key in
#            the keychain group.
#
# dev and release need the keychain-access-groups entitlement, which AMFI
# accepts only with a provisioning profile, so they follow this recipe:
# archive unsigned → ad-hoc sign the
# archived app with the entitlements → `xcodebuild -exportArchive` with method
# developer-id, which fetches the "Mac Team Direct" Developer ID profile and
# signs with "Developer ID Application" (team G5E484HA2U). That step talks to
# Apple and needs the team's signing identity in the login keychain.
#
# The guest kernel and initrd come from build/vault-guest/ (make vault-image,
# or VAULT_GUEST_DIR): Image and initrd.img are copied into
# Contents/Resources/guest/, and guest.lock.json's version, rootHash and
# hashOffset are compiled in (Sources/GuestPins.swift, generated). Without a
# guest the helper still builds, with empty pins, and reports image-missing.
#
# The flavor is also written into Info.plist as CinnaVaultFlavor (signed with
# the bundle), so packaging can refuse a non-release helper without running it.
set -eu

if [ "$(uname -s)" != "Darwin" ]; then
  echo "build-helper: not macOS, skipping"
  exit 0
fi

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="$ROOT/native/vault/helper"
GUEST="${VAULT_GUEST_DIR:-$ROOT/build/vault-guest}"
OUT_DIR="$ROOT/resources/vault"
FLAVOR="${FLAVOR:-test}"

case "$FLAVOR" in
  test) CONDITIONS="VAULT_TEST_GATE"; ENTITLEMENTS="$SRC/VaultHelper.test.entitlements" ;;
  dev) CONDITIONS="VAULT_DEV"; ENTITLEMENTS="$SRC/VaultHelper.dev.entitlements" ;;
  release) CONDITIONS=""; ENTITLEMENTS="$SRC/VaultHelper.entitlements" ;;
  *) echo "build-helper: FLAVOR must be test, dev or release (got $FLAVOR)" >&2; exit 2 ;;
esac

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
VERSION="$(node -p "require('$ROOT/package.json').version")"

# --- guest pins ---------------------------------------------------------------
PINS="$SRC/Sources/GuestPins.swift"
LOCK="$GUEST/guest.lock.json"
if [ -f "$LOCK" ] && [ -f "$GUEST/Image" ] && [ -f "$GUEST/initrd.img" ]; then
  node - "$LOCK" "$PINS" <<'JS'
const fs = require('node:fs')
const [lockPath, out] = process.argv.slice(2)
const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'))
const version = String(lock.version ?? '')
const rootHash = String(lock.rootHash ?? '')
const hashOffset = Number(lock.hashOffset)
if (!/^[A-Za-z0-9._+-]{1,64}$/.test(version)) throw new Error(`guest.lock.json: bad version ${version}`)
if (!/^[0-9a-f]{64}$/.test(rootHash)) throw new Error('guest.lock.json: rootHash must be 64 hex digits')
if (!Number.isSafeInteger(hashOffset) || hashOffset <= 0) throw new Error('guest.lock.json: bad hashOffset')
fs.writeFileSync(out, `// Generated by scripts/vault/build-helper.sh from build/vault-guest/guest.lock.json. Do not edit.
enum GuestPins {
  static let version = ${JSON.stringify(version)}
  static let rootHash = ${JSON.stringify(rootHash)}
  static let hashOffset: UInt64 = ${hashOffset}
}
`)
console.log(`build-helper: guest ${version}, root hash ${rootHash.slice(0, 12)}…, hash offset ${hashOffset}`)
JS
  HAVE_GUEST=1
else
  echo "build-helper: WARNING no guest image in $GUEST (make vault-image); the helper will report image-missing" >&2
  cat > "$PINS" <<'SWIFT'
// Generated by scripts/vault/build-helper.sh from build/vault-guest/guest.lock.json. Do not edit.
// Empty pins: built without a guest image; availability reports image-missing.
enum GuestPins {
  static let version = ""
  static let rootHash = ""
  static let hashOffset: UInt64 = 0
}
SWIFT
  HAVE_GUEST=0
fi

# --- compile -----------------------------------------------------------------
XC="xcodebuild -project $SRC/VaultHelper.xcodeproj -scheme VaultHelper -configuration Release -derivedDataPath $WORK/dd"
SETTINGS="CODE_SIGNING_ALLOWED=NO CODE_SIGN_ENTITLEMENTS= MARKETING_VERSION=$VERSION"
if [ "$FLAVOR" = test ]; then
  $XC build $SETTINGS "SWIFT_ACTIVE_COMPILATION_CONDITIONS=$CONDITIONS" > "$WORK/xcodebuild.log" 2>&1 \
    || { grep -E "error" "$WORK/xcodebuild.log" >&2; exit 1; }
  APP="$WORK/dd/Build/Products/Release/VaultHelper.app"
else
  $XC archive -archivePath "$WORK/VaultHelper.xcarchive" $SETTINGS "SWIFT_ACTIVE_COMPILATION_CONDITIONS=$CONDITIONS" \
    > "$WORK/xcodebuild.log" 2>&1 || { grep -E "error" "$WORK/xcodebuild.log" >&2; exit 1; }
  APP="$WORK/VaultHelper.xcarchive/Products/Applications/VaultHelper.app"
fi
[ -x "$APP/Contents/MacOS/VaultHelper" ] || { echo "build-helper: no binary in $APP" >&2; exit 1; }

# --- bundle contents ---------------------------------------------------------
/usr/libexec/PlistBuddy -c "Add :CinnaVaultFlavor string $FLAVOR" "$APP/Contents/Info.plist"
if [ "$HAVE_GUEST" = 1 ]; then
  mkdir -p "$APP/Contents/Resources/guest"
  cp "$GUEST/Image" "$GUEST/initrd.img" "$APP/Contents/Resources/guest/"
fi

# --- sign --------------------------------------------------------------------
codesign --force --sign - --options runtime --entitlements "$ENTITLEMENTS" "$APP"
if [ "$FLAVOR" != test ]; then
  xcodebuild -exportArchive -archivePath "$WORK/VaultHelper.xcarchive" -exportPath "$WORK/export" \
    -exportOptionsPlist "$SRC/export.plist" -allowProvisioningUpdates > "$WORK/export.log" 2>&1 \
    || { grep -E "error|rror:" "$WORK/export.log" >&2; exit 1; }
  APP="$WORK/export/VaultHelper.app"
  [ -f "$APP/Contents/embedded.provisionprofile" ] || { echo "build-helper: export embedded no provisioning profile" >&2; exit 1; }
  codesign -d --entitlements - "$APP" 2>/dev/null | grep -q "keychain-access-groups" \
    || { echo "build-helper: keychain-access-groups did not survive the export" >&2; exit 1; }
fi
codesign --verify --strict --deep "$APP"

mkdir -p "$OUT_DIR"
rm -rf "$OUT_DIR/VaultHelper.app"
# ditto keeps the signature's extended attributes and symlinks intact.
ditto "$APP" "$OUT_DIR/VaultHelper.app"
echo "build-helper: wrote $OUT_DIR/VaultHelper.app ($FLAVOR, $VERSION, guest: $([ "$HAVE_GUEST" = 1 ] && echo yes || echo none))"
